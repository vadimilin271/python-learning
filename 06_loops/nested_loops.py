#Квадрат из звёздочек — 5 × 5.
num = 5
for i in range(num):
    for j in range(num):
        print("*",end="")
    print()
#Треугольник:
#*
#**
#***
#****
#*****
num = 6
for i in range(1):
    for j in range(1,num):
        print("*"*j)
#Координаты — вывести все пары от (1, 1) до (3, 3) с помощью двух циклов.
for i in range(1,4):
    for j in range(1,4):
        print(i,j)
#Таблица умножения — от 1 до 10, используя два вложенных цикла.
for i in range(1,11):
    for j in range(1,11):
        print(f"{i} x {j} = {i*j}")
    print()
#Прямоугольник из звёздочек
