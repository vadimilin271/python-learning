#Пропуск чисел
#Даны числа от 1 до 20.
#- Выведи все числа.
#- Не выводи числа, которые делятся на 3 без остатка.
#- Используй continue.
for i in range(1,20+1):
    print(i)
for i in range(1,20+1):
    if i % 3 == 0:
        continue
    print(i)
#Остановка цикла
#Даны числа:
#numbers = [5, 12, 8, 20, 3, 15, 7]
#Перебери список и останови цикл, когда встретишь число больше 15. Само это число выводить не нужно.
numbers = [5, 12, 8, 20, 3, 15, 7]
for i in numbers:
    if i > 15:
       break
    print(i)
#Только чётные
#Даны числа от 1 до 30.
#- Выведи только чётные числа.
#- Используй continue, чтобы пропускать нечётные.
for i in range(1,31):
    if not i % 2 == 0:
        continue
    print(i)
#Прямоугольник из звёздочек
#Используя вложенные циклы, выведи прямоугольник размером 4 строки на 6 столбцов:
#******
#******
#******
#******
for i in range(4):
    for j in range(6):
        print("*",end="")
    print()
#Таблица умножения
#Используя два вложенных цикла, выведи таблицу умножения от 1 до 5.
#Например:
#1 x 1 = 1
#1 x 2 = 2
#...
#5 x 5 = 25
for i in range(1,6):
    for j in range(1,6):
        print(f"{i} x {j} = {i*j}")
    print()